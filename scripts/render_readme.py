def fmt_discovered_section(discovered, lang="en"):
    """Renderiza a seção '🔍 Auto-discovered Models' a partir do snapshot."""
    if not discovered:
        return ""

    ok = [(s, r) for s, r in discovered.items() if r.get("status") == "ok" and r.get("count", 0) > 0]
    empty = [(s, r) for s, r in discovered.items() if r.get("status") == "ok" and r.get("count", 0) == 0]
    auth = [(s, r) for s, r in discovered.items() if "auth" in r.get("status", "")]
    errors = [(s, r) for s, r in discovered.items()
              if r.get("status") not in ("ok",) and "auth" not in r.get("status", "")]
    # Providers que respondem 200 mas com 0 modelos viram "empty_response"
    for slug, r in empty:
        errors.append((slug, {**r, "status": "empty_response (200 but no models)"}))

    total_models = sum(r.get("count", 0) for _, r in ok)

    heading, summary, public, public_header, status_header, protected, failed = DISCOVERY_COPY[lang]
    lines = ["\n---\n", f"## 🔍 {heading}\n"]
    lines.append(f"> {summary.format(providers=len(ok), models=total_models)}\n")

    # Tabela principal: providers com /models público
    if ok:
        lines.append(f"### 🟢 {public}\n")
        lines.append(f"| {public_header} |")
        lines.append("|----------|------:|----------|")
        for slug, r in sorted(ok, key=lambda x: -x[1].get("count", 0)):
            count = r.get("count", 0)
            base = r.get("api_base", "—")
            lines.append(f"| `{slug}` | {count} | `{base}` |")
        lines.append("")

    # Auth-protected (collapsible)
    if auth:
        lines.append("<details>")
        lines.append(f"<summary>🔒 {protected.format(count=len(auth))}</summary>\n")
        lines.append(f"| {status_header} |")
        lines.append("|----------|--------|")
        for slug, r in sorted(auth):
            lines.append(f"| `{slug}` | {r.get('status')} |")
        lines.append("\n</details>\n")

    # Erros (collapsible)
    if errors:
        lines.append("<details>")
        lines.append(f"<summary>⚠️ {failed.format(count=len(errors))}</summary>\n")
        lines.append(f"| {status_header} |")
        lines.append("|----------|--------|")
        for slug, r in sorted(errors):
            lines.append(f"| `{slug}` | {r.get('status')} |")
        lines.append("\n</details>\n")

    return "\n".join(lines)


# Match only the section introduced by discover_models.py, and require the next
# top-level boundary to be its closing separator; never absorb another section.
DISCOVERY_SECTION = re.compile(
    r"^## 🔍 [^\n]+\n\n> [^\n]*scripts/discover_models\.py[^\n]*\n"
    r"(?:(?!^## |^---$).)*(?=^---$)",
    re.MULTILINE | re.DOTALL,
)


def discovery_span(text):
    matches = list(DISCOVERY_SECTION.finditer(text))
    if len(matches) != 1:
        return None
    match = matches[0]
    return match.start(), match.start() + len(match.group().rstrip("\n"))


def sha256_text(content):
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def sync_discovery_translations(before, after, discovered):
    """Update translations only if the previously synced source changed solely here."""
    i18n = ROOT / ".github/i18n"
    hash_file = i18n / ".source-hash"
    if before == after or not hash_file.is_file():
        return
    if hash_file.read_text(encoding="utf-8").strip() != sha256_text(before):
        return

    old_section, new_section = discovery_span(before), discovery_span(after)
    if old_section is None or new_section is None:
        return
    old_start, old_end = old_section
    new_start, new_end = new_section
    if (before[:old_start], before[old_end:]) != (after[:new_start], after[new_end:]):
        return

    # Check every file before writing any. A missing/malformed translation must
    # leave the recorded source hash untouched, so the standard guard fails.
    pending = {}
    for lang in LANGUAGES:
        translation = i18n / f"README.{lang}.md"
        if not translation.is_file():
            return
        text = translation.read_text(encoding="utf-8")
        span = discovery_span(text)
        if span is None:
            return
        start, end = span
        section = fmt_discovered_section(discovered, lang).removeprefix("\n---\n\n").rstrip("\n")
        pending[translation] = text[:start] + section + text[end:]
    for translation, text in pending.items():
        translation.write_text(text, encoding="utf-8")

    # Keep the full source hash: editorial/catalog drift still requires a
    # translation refresh. Only record it after all six documents were written.
    hash_file.write_text(sha256_text(after) + "\n", encoding="utf-8")


def main():
    hub = yaml.safe_load((ROOT / "data/hub.yaml").read_text())
    grouped = defaultdict(list)
    for e in hub:
        grouped[e["category"]].append(e)

    out = ["# 🌟 Free LLM Hub\n"]
    out.append("![Anchors](https://github.com/felipetruman/free-llm-hub/actions/workflows/check-anchors.yml/badge.svg)\n")
    out.append("> A unified, community-driven catalog of LLM APIs, inference engines, gateways, and the entire OSS LLM ecosystem.\n")
    out.append(f"**Total entries:** {len(hub)} • **Last updated:** auto-generated\n")
    out.append("\n## 📑 Table of Contents\n")
    for cat in CATEGORY_NAMES:
        if cat in grouped:
            slug_anchor = _slugify(CATEGORY_NAMES[cat])
            out.append(f"- [{CATEGORY_NAMES[cat]}](#{slug_anchor}) ({len(grouped[cat])})")
    out.append("\n---\n")

    for cat, items in sorted(grouped.items(), key=lambda x: list(CATEGORY_NAMES).index(x[0]) if x[0] in CATEGORY_NAMES else 999):
        title = CATEGORY_NAMES.get(cat, cat)
        out.append(f"\n## {title}\n")

        # Subscription plans: ordena por preço
        if cat == "subscription-plan":
            items = sorted(items, key=lambda x: (x.get("pricing", {}) or {}).get("monthly_usd") or 999999)

        out.append("| Name | Country | Pricing | Rate Limits | Models / Notes | Link |")
        out.append("|------|:-:|:-:|:-:|------|:-:|")
        for e in items:
            name = e["name"]
            country = e.get("country", "—")
            pricing = fmt_pricing(e.get("pricing"))
            limits = fmt_limits(e.get("rate_limits"))
            models = ", ".join((e.get("models") or [])[:3]) or e.get("notes") or "—"
            if len(models) > 60: models = models[:57] + "..."
            link = f"[🔗]({e.get('website', e.get('github', '#'))})"
            out.append(f"| **{name}** | {country} | {pricing} | {limits} | {models} | {link} |")

    # Seção auto-gerada de modelos descobertos via /v1/models
    discovered = load_discovered()
    discovered_md = fmt_discovered_section(discovered)
    if discovered_md:
        out.append(discovered_md)

    out.append("\n---\n")
    out.append("## 🤝 Contributing\n")
    out.append("Edit `data/0X-*.yaml`, run `./scripts/merge.sh && python scripts/render_readme.py`, open a PR.\n")
    out.append("## 📜 License\nMIT\n")

    rendered = "\n".join(out)
    # Inject language selector after H1 (single source of truth for i18n header)
    rendered = inject_selector(rendered, current_lang=None)
    source = ROOT / "README.md"
    if source.is_file():
        sync_discovery_translations(source.read_text(encoding="utf-8"), rendered, discovered)
    source.write_text(rendered, encoding="utf-8")
    print(f"✅ README.md gerado com {len(hub)} entradas")

if __name__ == "__main__":
    main()
